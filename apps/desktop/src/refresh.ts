/**
 * 手动刷新。
 *
 * **为什么必须有:** Quire 的全部立论是"文件是你的,爱怎么改怎么改"。
 * 可它在别人改完之后看不见 —— 用户在编辑器里补了一段批注,切回 Quire,
 * 列表还是旧的。没有文件监控的情况下,手动刷新就是那根救命的绳子:
 * 至少用户知道有这根绳子,而且拉一下就管用。
 *
 * 这里只放**不该被界面逻辑绕进去的那部分决定**,渲染和 IPC 留在 main.ts。
 */

/** 刷新之后列表该显示什么。 */
export type AfterRefresh = "same" | "reload";

/**
 * 刷新完了,该干什么。
 *
 * 关键在搜索框:**正在搜的时候刷新,不能把结果冲掉**。
 * 用户输入"rust",结果列了 8 条,他随手按一下 F5——列表忽然变成全库
 * 几百条,而搜索框里还写着 "rust"。他会以为搜索坏了。
 *
 * 所以:搜索框里有东西就重新搜一遍(后端那边还是按搜索过滤的),
 * 空的才回到全库。
 */
export function afterRefresh(query: string): AfterRefresh {
  return query.trim() === "" ? "reload" : "same";
}
